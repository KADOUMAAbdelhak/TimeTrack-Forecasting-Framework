"""Post-hoc check of A3's H-A3b statistic for units whose outer score is undefined (a zero S2 outer MAE).

    OMP_NUM_THREADS=1 PYTHONPATH=. old_fgcs_rejected/.venv_legacy/bin/python \
        manuscript/fgcs/tools/a3_zero_reference_check.py OUT.json

The frozen detection statistic (fgcs_strengthening_v04a3/gate.py, `detection`) divides seed-specific outer M1 MAE by S2
MAE per resource and horizon. Where an S2 outer MAE is exactly zero, the unit's outer score becomes infinite or
undefined, and the frozen Spearman ranks it rather than dropping it. This script reads the same frozen inputs through
the frozen A3 readers, reproduces the frozen rho of every frame exactly, then recomputes rho and its VM-cluster
interval without those units. It also writes the supplement note (supplement_source/a3_zero_note.tex).
Post hoc; descriptive. It changes no frozen output.
"""
from hashlib import sha256
import json
from pathlib import Path
import sys
import warnings

import numpy as np

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))

from fgcs_strengthening_v04.src.analysis.bootstrap import Draws, percentile_interval, spearman  # noqa: E402
from fgcs_strengthening_v04a3 import analyse_gate, gate  # noqa: E402

A3 = ROOT / "fgcs_strengthening_v04a3/runtime/analysis_a3.json"
A3_SHA = "33e11a858ea338b3c3ff25bec2f59527a3a2100a386658443def77956501cee0"


def main():
    out = Path(sys.argv[1])
    if out.exists():
        sys.exit(f"Refusing to overwrite {out}")
    if sha256(A3.read_bytes()).hexdigest() != A3_SHA:
        sys.exit("analysis_a3.json differs from its frozen digest")
    frozen = {(d["tier"], d["block"], d["backbone"]): d for d in json.loads(A3.read_text())["detection"]}
    warnings.simplefilter("ignore", RuntimeWarning)
    loaded = [analyse_gate.tier1_frame(b, analyse_gate.CONFIG["tier1"]["blocks"][b]) for b in analyse_gate.TIER1_BLOCKS]
    tier1 = [frame for frame, _ in loaded]
    tier1_draws = analyse_gate.BlockDraws({frame.block: len(frame.entities) for frame in tier1})
    tier2, _ = analyse_gate.tier2_frames()
    tier2_draws = Draws()
    rows = []
    for frame in tier1 + tier2:
        draws = tier1_draws if frame.tier == "tier1" else tier2_draws
        reference = frozen[frame.tier, frame.block, frame.backbone]
        again = gate.detection(frame, draws)
        if again["rho"] != reference["rho"] or again["interval"] != reference["interval"]:
            sys.exit(f"Frozen detection not reproduced: {frame.tier} {frame.block} {frame.backbone}")
        x = (frame.val["M1"] / frame.val["S2"]).mean(axis=-1)
        y = (frame.outer["M1"] / frame.outer["S2"]).mean(axis=(-1, -2))
        E = x.shape[0]
        xs, ys = x.reshape(E, -1), y.reshape(E, -1)
        finite = np.isfinite(ys)
        rho = float(spearman(xs[finite], ys[finite]))
        replicates = []
        for row in draws.indices(frame.block):
            keep = np.isfinite(ys[row])
            replicates.append(spearman(xs[row][keep], ys[row][keep]))
        interval, undefined = percentile_interval(np.array(replicates))
        result = {"rho": rho, "interval": interval}
        rows.append({"tier": frame.tier, "block": frame.block, "backbone": frame.backbone, "units": int(x.size),
                     "zero_S2_outer_cells": int((frame.outer["S2"] == 0).sum()),
                     "nonfinite_units": int((~finite).sum()),
                     "frozen": {"rho": reference["rho"], "interval": reference["interval"],
                                "verdict": gate.detection_verdict(reference)},
                     "without_nonfinite_units": {**result, "undefined_replicates": undefined,
                                                 "verdict": gate.detection_verdict(result)}})
    affected = [r for r in rows if r["nonfinite_units"]]
    changed = [r for r in rows if r["frozen"]["verdict"] != r["without_nonfinite_units"]["verdict"]]
    largest = max(abs(r["frozen"]["rho"] - r["without_nonfinite_units"]["rho"]) for r in rows)
    document = {"format": "fgcs-a3-zero-reference-check/1", "post_hoc": True, "source_sha256": A3_SHA,
                "frames": len(rows), "affected_frames": len(affected), "verdict_changes": len(changed),
                "largest_rho_change": largest, "rows": rows}
    encoded = json.dumps(document, indent=1, allow_nan=False) + "\n"
    out.write_text(encoded)

    def label(r):
        return f"{'tier-1' if r['tier'] == 'tier1' else 'tier-2 ' + gate_label(r['backbone'])} {r['block']}"

    note = (f"% Generated by manuscript/fgcs/tools/a3_zero_reference_check.py; do not edit by hand.\n"
            f"\\emph{{Post-hoc check of H-A3b.}} In {len(affected)} frames ("
            + "; ".join(f"{label(r)}: {r['nonfinite_units']} of {r['units']} units" for r in affected)
            + "), an S2 outer MAE of exactly zero at one horizon makes a unit's outer score undefined, and the frozen "
            "statistic ranks such units instead of dropping them. Recomputed without them, $\\rho$ changes by at most "
            f"{largest:.3f} and {'no' if not changed else len(changed)} verdict"
            f"{'' if len(changed) == 1 else 's'} change"
            f"{'s' if len(changed) == 1 else ''}"
            f" (output SHA-256 \\texttt{{\\seqsplit{{{sha256(encoded.encode()).hexdigest()}}}}}).\n")
    (ROOT / "manuscript/fgcs/supplement_source/a3_zero_note.tex").write_text(note)
    print(out, sha256(encoded.encode()).hexdigest(), f"affected {len(affected)}, verdict changes {len(changed)}, "
          f"largest rho change {largest:.4f}")


def gate_label(backbone):
    return {"LSTM": "LSTM", "DLinear": "DLinear", "PatchTST": "PatchTST-style",
            "iTransformer": "iTransformer-style"}[backbone]


if __name__ == "__main__":
    main()
