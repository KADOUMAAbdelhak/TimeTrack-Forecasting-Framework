              rf"269, per-VM seed spreads were at most {f(seeds['max_seed_spread_excluding_233_269'], 3)} native units. "
              rf"The negative direction is broad: the frozen class is {a['aggregation_checks']['M0:S1']['class']} with "
              rf"{a['aggregation_checks']['M0:S1']['counts']['vms'][0]}/10 VMs, 0/5 horizons, 0/5 folds and 0/3 seeds "
              rf"positive, a matched-cell median ratio of {f(checks['M0:S1']['median_ratio'], 3)} and a win rate of "
