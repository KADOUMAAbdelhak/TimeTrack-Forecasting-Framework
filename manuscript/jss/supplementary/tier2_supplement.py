#!/usr/bin/env python3
"""Render the tier-2 supplementary tables from frozen outputs only.

From the repository root:
    old_fgcs_rejected/.venv_legacy/bin/python manuscript/jss/supplementary/tier2_supplement.py

Reads, after checking their sha256:
    fgcs_strengthening_v04/runtime/analysis/analysis_v04.json
    fgcs_strengthening_v04/runtime/analysis/audits/dlinear_rnd_cpu_m0/summary.json
Writes manuscript/jss/supplementary/tier2_supplement.tex. Nothing is re-estimated; the only
arithmetic is display rounding, per-VM medians of D-4 cosines, and medians/ranges of D-1 values
over entity-fold rows for a compact summary.
"""

import hashlib
import json
from pathlib import Path
import statistics

SCRIPT = Path(__file__).resolve()
ROOT = SCRIPT.parents[3]
ANALYSIS = ROOT / "fgcs_strengthening_v04/runtime/analysis/analysis_v04.json"
AUDIT = ROOT / "fgcs_strengthening_v04/runtime/analysis/audits/dlinear_rnd_cpu_m0/summary.json"
HASHES = {ANALYSIS: "308841865ec87b04e10ecb64f20bc13ce2e671511a1574056028f7b5710dd17a",
          AUDIT: "88b6f56a81d2db8eb87a4d878569c95595c247f1368dd2c8460429dbbb9a1b58"}
OUT = SCRIPT.with_name("tier2_supplement.tex")
BLOCKS = ("fastStorage", "Rnd")
RES = ("CPU", "THROUGHPUT", "MEMORY", "DISK_WRITE")
LAB = {"CPU": "CPU", "THROUGHPUT": "Throughput", "MEMORY": "Memory", "DISK_WRITE": "Disk write"}
BB = ("LSTM", "DLinear", "PatchTST", "iTransformer")
CL = {"Broad Positive": "BP", "Conditionally Positive": "CP", "Neutral or Mixed": "N", "Broad Negative": "BN"}


def load(path):
    data = path.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != HASHES[path]:
        raise SystemExit(f"hash mismatch for {path}: {digest}")
    return json.loads(data)


def f(v, p=2, sign=False):
    if v is None:
        return "--"
    return format(v, f"{'+' if sign else ''}.{p}f").replace("-", "$-$")


def longtable(spec, caption, label, header, rows, note=None, size="small"):
    out = ["\\" + size, r"\setlength{\tabcolsep}{3pt}", rf"\begin{{longtable}}{{{spec}}}", rf"\caption{{{caption}}}\label{{{label}}}\\",
           r"\toprule", header + r" \\", r"\midrule", r"\endfirsthead", r"\toprule", header + r" \\", r"\midrule",
           r"\endhead", r"\bottomrule", r"\endfoot"]
    out += [" & ".join(r) + r" \\" for r in rows]
    out += [r"\end{longtable}", r"\normalsize\setlength{\tabcolsep}{4pt}"]
    if note:
        out += [r"\noindent{\footnotesize " + note + "}", ""]
    return "\n".join(out)


