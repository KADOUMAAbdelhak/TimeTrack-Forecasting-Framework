              rf"{f(checks['M1:M0']['recomputed_gain_percent'], 6, True)}\%, absolute difference "
              rf"{checks['M1:M0']['abs_diff']:.1e}), and per-VM log effects agree to within "
              rf"{max(c['max_abs_diff_entity_log_effect'] for c in checks.values()):.0e}. Mean persistence skill "
