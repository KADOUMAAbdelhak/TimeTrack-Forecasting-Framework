              rf"({f(sk['M0']['per_vm']['269'], 2, True)}). All {a['source']['rows']:,} native-MAE rows were finite "
              r"and complete, with no zero-persistence cell.".replace(",", "{,}"),
              "",
              longtable("@{}lrrrrrrrr@{}", "DLinear Rnd CPU audit: per-VM seed-averaged native MAE, gains and each "
                        "VM's share of the summed M0$-$S1 excess.", "tab:supp-t2-audit",
                        r"VM & S1 & S2 & M0 & M1 & $G$(M0:S1) & $G$(M1:M0) & Share (\%) & Persistence MAE", rows,
                        "Gains in percent; MAE in native CPU units."),
              rf"VM233 contributes {f(100 * next(v['share_of_M0_minus_S1_excess'] for v in a['per_vm'] if v['vm'] == '233'), 1)}\% "
              r"of the summed M0$-$S1 excess. Its M0 MAE exceeds S1 in every fold (ratios "
              + ", ".join(f(r, 2) for r in next(v["fold_ratio_M0_over_S1"] for v in a["per_vm"] if v["vm"] == "233"))
              + r") and every seed (M0 " + ", ".join(f(x, 2) for x in seeds["vm233_M0_seeds"])
