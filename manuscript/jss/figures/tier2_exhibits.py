#!/usr/bin/env python3
"""Render the tier-2 (v0.4) manuscript exhibits from the frozen analysis output only.

From the repository root:
    old_fgcs_rejected/.venv_legacy/bin/python manuscript/jss/figures/tier2_exhibits.py

Reads only fgcs_strengthening_v04/runtime/analysis/analysis_v04.json, after checking its
sha256. Writes:
    manuscript/jss/tables/tier2_baseline_accuracy.tex
    manuscript/jss/tables/tier2_diagnostics.tex
    manuscript/jss/figures/tier2_contrast_matrix.pdf
    manuscript/jss/figures/tier2_mechanism.pdf
No scientific quantity is re-estimated. The only arithmetic is presentation: each
backbone's MacroMAE divided by the smallest MacroMAE in its row (baseline table), and
rounding for display.
"""

from __future__ import annotations

import hashlib
import json
import math
from pathlib import Path

SCRIPT = Path(__file__).resolve()
ROOT = SCRIPT.parents[3]
ANALYSIS = ROOT / "fgcs_strengthening_v04/runtime/analysis/analysis_v04.json"
ANALYSIS_SHA256 = "308841865ec87b04e10ecb64f20bc13ce2e671511a1574056028f7b5710dd17a"
TABLES = SCRIPT.parents[1] / "tables"
FIGURES = SCRIPT.parent

BLOCKS = ("fastStorage", "Rnd")
RESOURCES = ("CPU", "THROUGHPUT", "MEMORY", "DISK_WRITE")
LABEL = {"CPU": "CPU", "THROUGHPUT": "Throughput", "MEMORY": "Memory", "DISK_WRITE": "Disk write"}
SHORT = {"CPU": "CPU", "THROUGHPUT": "Thr", "MEMORY": "Mem", "DISK_WRITE": "Disk"}
BACKBONES = ("LSTM", "DLinear", "PatchTST", "iTransformer")
BB_LABEL = {"LSTM": "LSTM", "DLinear": "DLinear", "PatchTST": "PatchTST", "iTransformer": "iTrans."}
CONTRASTS = (("S2:S1", "(a) Context, independent: S2 vs S1"), ("M1:M0", "(b) Context, shared: M1 vs M0"),
             ("M0:S1", "(c) Sharing, own input: M0 vs S1"), ("M1:S2", "(d) Sharing, all input: M1 vs S2"))
CLASS = {"Broad Positive": "BP", "Conditionally Positive": "CP", "Neutral or Mixed": "N", "Broad Negative": "BN"}
COLOUR_LIMIT = 150.0
HEADER = f"% Generated by manuscript/jss/figures/tier2_exhibits.py from analysis_v04.json (sha256 {ANALYSIS_SHA256}).\n"


def load():
    data = ANALYSIS.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != ANALYSIS_SHA256:
        raise SystemExit(f"analysis_v04.json hash mismatch: {digest}")
    document = json.loads(data)
    if document["format"] != "fgcs-v04-analysis/1":
        raise SystemExit("unexpected analysis format")
    return document["results"]


def num(value, places=2, sign=False):
    return "--" if value is None else format(value, f"{'+' if sign else ''}.{places}f").replace("-", "$-$")


# -- tables ---------------------------------------------------------------------------------------

def baseline_table(P4):
    rows = {(r["block"], r["cell"], r["resource"]): r for r in P4["baseline_accuracy"]}
    cells = ("S2", "M1")
    lines = [HEADER, r"\begin{table*}[t]",
             r"  \caption{Tier-2 baseline accuracy on the 20-VM Bitbrains cohort: (A) each backbone's resource-overall "
             r"MacroMAE divided by the smallest MacroMAE among the defined backbones in that row (1.00 marks the most "
             r"accurate); (B) mean persistence skill. Descriptive only.}",
             r"  \label{tab:tier2-baseline}", r"  \centering", r"  \small", r"  \setlength{\tabcolsep}{3pt}",
             r"  \begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}ll" + "r" * 8 + "@{}}", r"    \toprule"]
    head = " & ".join(BB_LABEL[b] for b in BACKBONES)
    group = r"    & & \multicolumn{4}{c}{S2 (all input, independent)} & \multicolumn{4}{c}{M1 (all input, shared)} \\"
    rule = r"    \cmidrule(lr){3-6}\cmidrule(l){7-10}"
    for panel, title in (("ratio", r"\textbf{A:} MacroMAE ratio to the most accurate backbone"),
                         ("skill", r"\textbf{B:} Mean persistence skill")):
        lines += [rf"    \multicolumn{{10}}{{l}}{{{title}}} \\", group, rule,
                  rf"    Block & Resource & {head} & {head} \\", r"    \midrule"]
        for block in BLOCKS:
            for k, resource in enumerate(RESOURCES):
                values = []
                for cell in cells:
                    entries = rows[block, cell, resource]["backbones"]
                    best = min(e["macro_mae"] for e in entries.values())
                    for b in BACKBONES:
                        e = entries.get(b)
                        if e is None:
                            values.append("--")
                        elif panel == "ratio":
                            text = num(e["macro_mae"] / best)
                            values.append(r"\textbf{" + text + "}" if e["macro_mae"] == best else text)
                        else:
                            values.append(num(e["persistence_skill"], sign=True))
                lines.append(f"    {block if k == 0 else ''} & {LABEL[resource]} & " + " & ".join(values) + r" \\")
        lines.append(r"    \midrule" if panel == "ratio" else r"    \bottomrule")
    lines += [r"  \end{tabular*}", "",
              r"  \vspace{2pt}",
              r"  \parbox{\textwidth}{\footnotesize Ten VMs per block, three seeds, frozen H64-M1 contexts imposed on every "
              r"backbone, fixed untuned hyperparameters. iTransformer is defined only for S2 and M1. Backbones are compared on "
              r"their common available units (no unit was missing). S1 and M0 rows are in the supplement.}",
              r"\end{table*}", ""]
    return "\n".join(lines)


def diagnostics_table(P5):
    lines = [HEADER, r"\begin{table*}[t]",
             r"  \caption{Tier-2 mechanism diagnostics (descriptive associations, LSTM). (A) D-3: Spearman $\rho$ across "
             r"the ten VMs of each block between a dependence measure (D-1 training-window cross-correlation; D-2 "
             r"post-hoc Ridge ARX:AR gain) and the LSTM entity log effects $D$(S2:S1) and $D$(M1:S2), with VM-cluster "
             r"bootstrap 95\% intervals. (B) D-4 at the selected epoch and D-7 at the selected epoch.}",
             r"  \label{tab:tier2-diagnostics}", r"  \centering", r"  \small", r"  \setlength{\tabcolsep}{3pt}",
             r"  \begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lll" + "r" * 4 + "@{}}", r"    \toprule",
             r"    \multicolumn{7}{l}{\textbf{A:} D-3 dependence versus effect, $\rho$ [95\% interval]} \\",
             r"    & & & \multicolumn{2}{c}{D-1 (cross-correlation)} & \multicolumn{2}{c}{D-2 (Ridge ARX:AR)} \\",
             r"    \cmidrule(lr){4-5}\cmidrule(l){6-7}",
             r"    Block & Resource & & $D$(S2:S1) & $D$(M1:S2) & $D$(S2:S1) & $D$(M1:S2) \\", r"    \midrule"]
    d3 = {(r["dependence"], r["block"], r["resource"], r["effect"]): r for r in P5["D-3"]}

    def cell(r):
        lo, hi = r["interval"]
        mark = r"$^{*}$" if lo > 0 or hi < 0 else ""
        return f"{num(r['rho'], sign=True)} [{num(lo)}, {num(hi)}]{mark}"

    for block in BLOCKS:
        for k, resource in enumerate(RESOURCES):
            values = [cell(d3[dep, block, resource, eff]) for dep in ("D-1", "D-2") for eff in ("D(S2:S1)", "D(M1:S2)")]
            lines.append(f"    {block if k == 0 else ''} & {LABEL[resource]} & & " + " & ".join(values) + r" \\")
    lines += [r"    \midrule",
              r"    \multicolumn{7}{l}{\textbf{B:} D-4 gradient statistics (VM medians) and D-7 M1 training-loss shares} \\",
              r"    Block & Formulation & & Excess conflict $K$ & Median $|\cos|$ & Norm ratio max/min & \\", r"    \midrule"]
    groups = {}
    for r in P5["D-4"]:
        groups.setdefault((r["block"], r["formulation"], r["role"]), []).append(r)
    for block in BLOCKS:
        for formulation, role in (("M1", "primary"), ("M0", "descriptive")):
            rows = groups[block, formulation, role]
            k = median([r["K"] for r in rows])
            cos = median([median([abs(c) for c in r["cosines"].values()]) for r in rows])
            ratio = median([r["norm_ratio"] for r in rows])
            lines.append(f"    {block if formulation == 'M1' else ''} & {formulation} ({role}) & & {num(k, 3, True)} & "
                         f"{num(cos, 3)} & {num(ratio, 1)} & \\\\")
    d7 = {(r["block"], r["resource"]): r for r in P5["D-7"]}
    lines += [r"    \midrule", r"    Block & & & " + " & ".join(LABEL[r] for r in RESOURCES) + r" \\", r"    \midrule"]
    for block in BLOCKS:
        lines.append(f"    {block} & D-7 share at $E$ & & " + " & ".join(num(d7[block, r]["mean_share_at_E"], 3)
                                                                     for r in RESOURCES) + r" \\")
    lines += [r"    \bottomrule", r"  \end{tabular*}", "", r"  \vspace{2pt}",
              r"  \parbox{\textwidth}{\footnotesize $^{*}$Interval excludes zero. Intervals reuse each block's shared "
              r"VM-cluster bootstrap draw matrix (10{,}000 replicates, seed 20261007). D-2 reuses post-hoc Ridge outcomes already observed. "
              r"Excess conflict $K$ is the cross-task minus same-task gradient sign-conflict rate over eight keyed batch "
              r"pairs; the $|\cos|$ column is the median over VMs of each VM's median absolute value of the six "
              r"pairwise task-gradient cosines. D-7 is each task's mean "
              r"share of M1 training MSE at the selected epoch $E$ (shares sum to one). No p-values; associations only.}",
              r"\end{table*}", ""]
    return "\n".join(lines)


def median(values):
    values = sorted(values)
    n = len(values)
    return values[n // 2] if n % 2 else (values[n // 2 - 1] + values[n // 2]) / 2


# -- figures --------------------------------------------------------------------------------------

def style():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 8, "pdf.fonttype": 42, "ps.fonttype": 42,
                         "axes.linewidth": 0.6, "svg.hashsalt": "tier2", "pdf.compression": 9})
    return plt


def contrast_matrix(P4):
    plt = style()
    from matplotlib.colors import LinearSegmentedColormap
    from matplotlib.patches import Rectangle
    cmap = LinearSegmentedColormap.from_list("signed", ["#b2182b", "#f7f7f7", "#2166ac"])
    rows = {(r["backbone"], r["block"], r["resource"], r["contrast"]): r for r in P4["contrasts"]}
    general = {(r["block"], r["contrast"], r["resource"]) for r in P4["cross_backbone"]
               if r["summary"] == "generalises across backbones"}

    def colour(g):
        if abs(g) > COLOUR_LIMIT:
            raise SystemExit("colour scale would clip a value")
        return cmap(0.5 + math.asinh(g) / (2 * math.asinh(COLOUR_LIMIT)))

    fig, axes = plt.subplots(2, 2, figsize=(174 / 25.4, 150 / 25.4))
    for ax, (contrast, title) in zip(axes.flat, CONTRASTS):
        ax.set_xlim(-0.75, 4.65); ax.set_ylim(0, 9.15); ax.axis("off"); ax.invert_yaxis()
        ax.set_title(title, fontsize=8.5, fontweight="bold", loc="left")
        for j, resource in enumerate(RESOURCES):
            ax.text(0.6 + j + 0.5, 0.3, LABEL[resource], ha="center", va="center", fontsize=7.5)
        y = 0.6
        for block in BLOCKS:
            ax.text(-0.62, y + 2.0, block, rotation=90, ha="center", va="center", fontsize=7.5, fontweight="bold")
            for backbone in BACKBONES:
                ax.text(0.55, y + 0.5, BB_LABEL[backbone], ha="right", va="center", fontsize=7.3)
                for j, resource in enumerate(RESOURCES):
                    x = 0.6 + j
                    r = rows.get((backbone, block, resource, contrast))
                    if r is None:
                        ax.add_patch(Rectangle((x, y), 1, 1, facecolor="white", edgecolor="#bbbbbb", hatch="////",
                                               linewidth=0.4))
                        continue
                    g = r["gain_percent"]
                    fill = colour(g)
                    ax.add_patch(Rectangle((x, y), 1, 1, facecolor=fill, edgecolor="white", linewidth=0.8))
                    lum = 0.2126 * fill[0] + 0.7152 * fill[1] + 0.0722 * fill[2]
                    ink = "white" if lum < 0.45 else "black"
                    mark = ""
                    if backbone == "DLinear" and block == "Rnd" and resource == "CPU" and contrast in ("M0:S1", "M1:M0"):
                        mark = "†"
                    ax.text(x + 0.5, y + 0.36, f"{g:+.2f}{mark}", ha="center", va="center", fontsize=6.8, color=ink)
                    ax.text(x + 0.5, y + 0.72, CLASS[r["class"]], ha="center", va="center", fontsize=6.0, color=ink)
                    if (block, contrast, resource) in general:
                        ax.add_patch(Rectangle((x + 0.03, y + 0.03), 0.94, 0.94, fill=False, edgecolor="black",
                                               linewidth=1.3))
                y += 1
            y += 0.4
    fig.text(0.01, 0.012,
             "Gain G (%) = 100(B − C)/B, MacroMAE; positive favours the candidate. Classes: BP broad positive, "
             "CP conditionally positive,\nN neutral or mixed, BN broad negative. Hatched: undefined cell. Black frame: "
             "effect generalises across backbones.\n† Scale-dominated by one VM (see text). Colour: symmetric asinh "
             "aid, unclipped; printed values are authoritative.", fontsize=6.6, va="bottom")
    fig.subplots_adjust(left=0.01, right=0.995, top=0.965, bottom=0.085, wspace=0.03, hspace=0.1)
    out = FIGURES / "tier2_contrast_matrix.pdf"
    fig.savefig(out, metadata={"CreationDate": None, "ModDate": None, "Producer": None, "Creator": None})
    plt.close(fig)
    return out


def mechanism(P5):
    plt = style()
    import numpy as np
    colours = {"CPU": "#1b9e77", "THROUGHPUT": "#d95f02", "MEMORY": "#7570b3", "DISK_WRITE": "#e7298a"}
    marker = {"fastStorage": "o", "Rnd": "s"}
    fig = plt.figure(figsize=(174 / 25.4, 120 / 25.4))
    outer = fig.add_gridspec(2, 1, height_ratios=(1, 1), hspace=0.5)
    grid = outer[0].subgridspec(1, 4, wspace=0.55)
    lower = outer[1].subgridspec(1, 4, wspace=0.3)
    ax = fig.add_subplot(grid[0, 0:2])
    for block in BLOCKS:
        pts = [r for r in P5["D-4"] if r["block"] == block and r["formulation"] == "M1"]
        ax.scatter([r["norm_ratio"] for r in pts], [r["K"] for r in pts], marker=marker[block], s=16,
                   facecolor="none" if block == "Rnd" else "#444444", edgecolor="#444444", linewidth=0.7, label=block)
    ax.axhline(0, color="#999999", linewidth=0.6, linestyle="--")
    ax.set_xscale("log"); ax.set_xlabel("Task-gradient norm ratio max/min (log)"); ax.set_ylabel("Excess conflict K")
    ax.set_title("(a) D-4: LSTM M1 shared encoder, per VM", fontsize=8, loc="left", fontweight="bold")
    from matplotlib.lines import Line2D
    handles = [Line2D([], [], linestyle="none", marker=marker[b], markersize=4.5, markerfacecolor=f,
                      markeredgecolor="#444444") for b, f in (("fastStorage", "#444444"), ("Rnd", "none"))]
    ax.legend(handles, BLOCKS, fontsize=6.8, frameon=False, loc="lower right")
    for k, block in enumerate(BLOCKS):
        ax = fig.add_subplot(grid[0, 2 + k])
        for r in [r for r in P5["D-7"] if r["block"] == block]:
            full = [e for e in r["per_epoch"] if 2 * e["fits"] >= r["fits"]]
            tail = [e for e in r["per_epoch"] if e["epoch"] >= full[-1]["epoch"]]
            ax.plot([e["epoch"] for e in full], [e["mean_share"] for e in full], color=colours[r["resource"]],
                    linewidth=1.0, label=LABEL[r["resource"]])
            ax.plot([e["epoch"] for e in tail], [e["mean_share"] for e in tail], color=colours[r["resource"]],
                    linewidth=0.6, linestyle=":")
        ax.axhline(0.25, color="#999999", linewidth=0.6, linestyle="--")
        ax.set_ylim(0, 0.6); ax.set_xlabel("Epoch")
        if k == 0:
            ax.set_ylabel("Share of M1 training MSE")
        ax.set_title(f"({'b' if k == 0 else 'c'}) D-7: {block}", fontsize=8, loc="left", fontweight="bold")
        if k == 1:
            ax.legend(fontsize=6.2, frameon=False, loc="upper right", handlelength=1.2)
    d6 = {(r["estimand"], r["block"], r["target"], r["source"]): r for r in P5["D-6"]}
    letters = iter("defg")
    vmax = max(abs(r["median"]) for r in P5["D-6"])
    for k, (estimand, block) in enumerate((("F", "fastStorage"), ("F", "Rnd"), ("Q", "fastStorage"), ("Q", "Rnd"))):
        ax = fig.add_subplot(lower[0, k])
        m = np.full((4, 4), np.nan)
        for i, t in enumerate(RESOURCES):
            for j, s in enumerate(RESOURCES):
                if i != j:
                    m[i, j] = d6[estimand, block, t, s]["median"]
        image = ax.imshow(m, cmap="RdBu", vmin=-vmax, vmax=vmax)
        for i, t in enumerate(RESOURCES):
            for j, s in enumerate(RESOURCES):
                if i != j:
                    r = d6[estimand, block, t, s]
                    fill = image.cmap(image.norm(r["median"]))
                    ink = "white" if 0.2126 * fill[0] + 0.7152 * fill[1] + 0.0722 * fill[2] < 0.45 else "black"
                    label = f"{r['median']:+.3f}".replace("0.", ".", 1)
                    ax.text(j, i, f"{label}\n{r['positive_entities']}/{r['entities']}", ha="center",
                            va="center", fontsize=6.5, linespacing=1.05, color=ink)
        ax.set_xticks(range(4), [SHORT[r] for r in RESOURCES], fontsize=6.5)
        ax.set_yticks(range(4), [SHORT[r] for r in RESOURCES], fontsize=6.5)
        ax.set_xlabel("Source j" if estimand == "F" else "Omitted j", fontsize=7)
        if k == 0:
            ax.set_ylabel("Target i", fontsize=7)
        ax.set_title(f"({next(letters)}) D-6 {estimand}: {block}", fontsize=8, loc="left", fontweight="bold")
    cax = fig.add_axes([0.905, 0.1, 0.012, 0.28])
    bar = fig.colorbar(image, cax=cax)
    bar.ax.tick_params(labelsize=6)
    bar.set_label("Median over VMs", fontsize=6.5)
    fig.subplots_adjust(left=0.08, right=0.885, top=0.95, bottom=0.1)
    out = FIGURES / "tier2_mechanism.pdf"
    fig.savefig(out, metadata={"CreationDate": None, "ModDate": None, "Producer": None, "Creator": None})
    plt.close(fig)
    return out


def main():
    results = load()
    outputs = []
    for name, text in (("tier2_baseline_accuracy.tex", baseline_table(results["P4"])),
                       ("tier2_diagnostics.tex", diagnostics_table(results["P5"]))):
        path = TABLES / name
        path.write_text(text)
        outputs.append(path)
    outputs.append(contrast_matrix(results["P4"]))
    outputs.append(mechanism(results["P5"]))
    for path in outputs:
        print(hashlib.sha256(path.read_bytes()).hexdigest(), path.relative_to(ROOT))


if __name__ == "__main__":
    main()
