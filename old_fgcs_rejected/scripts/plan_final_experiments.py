"""Estimate final FGCS experiment compute before freeze."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from timetrack.final_config import validate_final_config


def plan(cfg: dict) -> dict:
    hierarchies = ["memory_um", "cpu_core_weighted", "disk_ud"]
    # network: admit up to 2 bond0 hierarchies if threshold passes
    n_network = 2
    n_hier = len(hierarchies) + n_network

    series_per = 8  # 7 bottom + 1 top
    horizons = list(cfg["horizons"])
    n_folds = int(cfg["folds"]["n_outer"])
    seeds = cfg["seeds"]
    models = list(cfg["models"])

    def n_seeds(m: str) -> int:
        return len(seeds.get(m) or [0])

    # Context selected once per (model, series, horizon, fold) via inner val — count as 1 fit after selection
    # Base fits: hierarchy × series × horizon × fold × model_seed
    base_fits = 0
    for m in models:
        base_fits += n_hier * series_per * len(horizons) * n_folds * n_seeds(m)

    methods = list(cfg["reconciliation_methods"])
    nn = len(cfg.get("nonnegative_ablation") or [False])
    # Recon evaluations reuse base forecasts
    recon_evals = n_hier * len(horizons) * n_folds * sum(n_seeds(m) for m in models) * len(methods) * nn

    budgets = (cfg.get("hpo") or {}).get("budgets") or {}
    # HPO per (model, series, horizon, outer fold) on primary hierarchies only (memory+cpu+disk)
    hpo_hier = 3
    hpo_trials = 0
    for m, b in budgets.items():
        hpo_trials += hpo_hier * series_per * len(horizons) * n_folds * int(b)

    # Rough timings (seconds) from development screens
    sec_per_fit = {
        "persistence": 0.05,
        "ridge": 0.4,
        "lightgbm": 3.0,
        "lstm": 25.0,
        "dlinear": 15.0,
    }
    cpu_sec = 0.0
    for m in models:
        cpu_sec += n_hier * series_per * len(horizons) * n_folds * n_seeds(m) * sec_per_fit.get(m, 5.0)
    # HPO multiplies tunable models
    for m, b in budgets.items():
        cpu_sec += hpo_hier * series_per * len(horizons) * n_folds * int(b) * 0.35 * sec_per_fit.get(m, 5.0)
    cpu_hours = cpu_sec / 3600.0

    # Disk: lightweight CSVs + optional caches (no raw preds in git)
    disk_gb = (base_fits * 2_000 + recon_evals * 1_500 + hpo_trials * 500) / 1e9
    disk_gb = max(0.05, disk_gb) + 0.5  # + manifests/figures

    artifact_count = (
        10  # required metric CSVs
        + 8  # tables
        + 8  # figures
        + base_fits  # optional run caches (gitignored)
    )

    return {
        "n_hierarchies_planned": n_hier,
        "total_unique_base_model_fits": int(base_fits),
        "total_reconciliation_evaluations": int(recon_evals),
        "hpo_trial_count": int(hpo_trials),
        "expected_cpu_hours": round(cpu_hours, 1),
        "expected_disk_usage_gb": round(disk_gb, 2),
        "expected_artifact_count": int(artifact_count),
        "expected_per_stage_runtime_hours": {
            "base_fits": round((cpu_sec * 0.45) / 3600, 1),
            "hpo": round((cpu_sec * 0.45) / 3600, 1),
            "reconciliation_stats_reporting": round((cpu_sec * 0.10) / 3600, 1),
        },
        "retry_budget": {"max_retries_per_run": 1, "skip_on_persistent_timeout": True},
        "timeout_policy": cfg.get("timeouts"),
        "notes": [
            "Estimates assume fixed post-HPO context (not refitting all contexts).",
            "Lower HPO budgets before freeze if CPU-hours exceed available wall-clock.",
            "DLinear remains timeout-bounded; failures recorded as metadata.",
        ],
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", type=Path, default=ROOT / "configs" / "final_fgcs.yaml")
    args = ap.parse_args()
    cfg = yaml.safe_load(args.config.read_text())
    errs = validate_final_config(cfg, require_frozen=False)
    if errs:
        print("INVALID CONFIG")
        for e in errs:
            print("-", e)
        sys.exit(1)
    out = plan(cfg)
    print(json.dumps(out, indent=2))
    docs = ROOT / "docs" / "FINAL_EXPERIMENT_PLAN.md"
    lines = [
        "# Final Experiment Plan (FGCS C1)",
        "",
        "Generated by `scripts/plan_final_experiments.py` prior to freeze.",
        "",
        f"- Unique base-model fits: **{out['total_unique_base_model_fits']}**",
        f"- Reconciliation evaluations: **{out['total_reconciliation_evaluations']}**",
        f"- HPO trials: **{out['hpo_trial_count']}**",
        f"- Expected CPU-hours: **{out['expected_cpu_hours']}**",
        f"- Expected disk (GB): **{out['expected_disk_usage_gb']}**",
        f"- Expected artifact count: **{out['expected_artifact_count']}**",
        "",
        "## Per-stage runtime (hours)",
        "",
        "```json",
        json.dumps(out["expected_per_stage_runtime_hours"], indent=2),
        "```",
        "",
        "## Retry / timeout",
        "",
        "```json",
        json.dumps({"retry": out["retry_budget"], "timeouts": out["timeout_policy"]}, indent=2),
        "```",
        "",
        "## Notes",
        "",
    ]
    for n in out["notes"]:
        lines.append(f"- {n}")
    lines.append("")
    lines.append("## Freeze gate")
    lines.append("")
    lines.append("Do not freeze if CPU-hours are unexpectedly unbounded or smoke fails.")
    lines.append("")
    docs.write_text("\n".join(lines))
    print(f"Wrote {docs}")


if __name__ == "__main__":
    main()
